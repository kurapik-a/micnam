/*
 * jy61p.c - 维特智能 JY61P 姿态传感器驱动 (休眠模块, 预留)
 *
 * 历史: 最初走 I2C 读取, 实测无法与 JY61P 通信, 改用 UART3 (PB10/PB11) 串口直读角度;
 *       注意 UART3 与 I2C2 引脚复用, 不可同时使用。
 * 协议: 维特智能定长帧, 帧头 0x55 + 类型字节:
 *       0x51 加速度帧 (AX/AY/AZ + 温度) / 0x52 角速度帧 / 0x53 角度帧,
 *       每帧 11 字节 (帧头2 + 数据8 + 校验1), 一个数据包三帧连续共 33 字节。
 */

#include "jy61p.h"

/*
 * I2C 方式读寄存器 (保留: 实测 I2C 无法与 JY61P 通信, 当前未启用)
 * reg: 寄存器地址, 常用 AX=52 / AY=53 / ... / Yaw=63
 * dat: 输出 12 组 16-bit 值 (高字节在前)
 */
void JY61P_I2C_read(uint16_t reg, uint16_t *dat)
{
    uint8_t pdata[24];
    /* 组合格式读: 先写寄存器地址 (0xA0 写地址), 再重复起始读 (库内部用读地址)。
       注意: 原 split 写法 (写地址带 STOP + 再读) 对该 IMU 会读到错误值, 必须组合读。 */
    I2Cy_ReadReg(0xA0, (uint8_t)(reg & 0xFF), pdata, 3);
    /* 拼 12 组 16-bit 值 (高字节在前) */
    for (int i = 0; i < 12; i++)
        dat[i] = ((uint16_t)pdata[i * 2] << 8) | pdata[i * 2 + 1];
}

/*
 * 解析 UART3 收到的 33 字节数据包 (三帧连续: 加速度/角速度/角度)
 * C:  数据包首地址
 * G:  输出加速度 g      (/32767 * 16g)
 * AW: 输出角速度 deg/s  (/32767 * 2000deg/s)
 * A:  输出角度 deg      (/32767 * 180deg)
 * T:  输出温度 degC     (/100)
 */
void get_JY61P(u8 *C, float *G, float *AW, float *A, float *T)
{
    char sum1, sum2, sum3;
    sum1 = C[0] + C[1] + C[2] + C[3] + C[4] + C[5] + C[6] + C[7] + C[8] + C[9];
    sum2 = C[11] + C[12] + C[13] + C[14] + C[15] + C[16] + C[17] + C[18] + C[19] + C[20];
    sum3 = C[22] + C[23] + C[24] + C[25] + C[26] + C[27] + C[28] + C[29] + C[30] + C[31];

    if (C[0] == 0X55 && C[1] == 0X51)   // 加速度帧 (含温度)
    {
        if (C[10] == sum1)              // 校验和
        {
            G[0] = (float)((short)(C[3] << 8) + C[2]) / 32767 * 16;
            G[1] = (float)((short)(C[5] << 8) + C[4]) / 32767 * 16;
            G[2] = (float)((short)(C[7] << 8) + C[6]) / 32767 * 16;
            *T   = (float)(short)((C[9] << 8) + C[8]) / 100;
        }
    }
    if (C[11] == 0X55 && C[12] == 0X52) // 角速度帧
    {
        if (C[21] == sum2)              // 校验和
        {
            AW[0] = (float)((short)(C[14] << 8) + C[13]) / 32767 * 2000;
            AW[1] = (float)((short)(C[16] << 8) + C[15]) / 32767 * 2000;
            AW[2] = (float)((short)(C[18] << 8) + C[17]) / 32767 * 2000;
        }
    }
    if (C[22] == 0X55 && C[23] == 0X53) // 角度帧 (欧拉角)
    {
        if (C[32] == sum3)              // 校验和
        {
            A[0] = (float)((short)(C[25] << 8 | C[24])) / 32767.0f * 180.0f;
            A[1] = (float)((short)(C[27] << 8 | C[26])) / 32767.0f * 180.0f;
            A[2] = (float)((short)(C[29] << 8 | C[28])) / 32767.0f * 180.0f;
        }
    }
}
